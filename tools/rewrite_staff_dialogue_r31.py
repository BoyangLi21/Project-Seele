def main():
    current = json.loads(PATH.read_text(encoding='utf8'))
    assert set(current['profiles']) == set(PROFILES)
    for name, old in current['profiles'].items():
        assert set(old) == set(PROFILES[name]), name
        for topic, lines in PROFILES[name].items():
            assert 1 <= len(lines) <= 16 and all(0 < len(line) <= 240 for line in lines)
    current['profiles'] = PROFILES
    PATH.write_text(json.dumps(current, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
    print('Rewritten', sum(len(lines) for p in PROFILES.values() for lines in p.values()), 'lines; original topics preserved.')

if __name__ == '__main__':
    main()
